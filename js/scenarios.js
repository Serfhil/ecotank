'use strict';
// Сценарии — способы играть: что происходит на поле, откуда берутся враги и чем заканчивается бой.
// Ядро (game.js, ИИ, оружие, отрисовка) не знает ни одного сценария по имени: оно вызывает только
// необязательные функции активного сценария из списка ниже. Проверки вида `if (raseiniai)` в ядре запрещены.
//
// Новый сценарий — новый файл js/scenario-<имя>.js с одним вызовом defineScenario() и строкой <script>
// в index.html после game.js. Если ядру не хватает точки расширения, она добавляется в этот список
// и вызывается из ядра для всех сценариев одинаково.
//
// Поля и функции сценария (обязательна только start):
//   start(retry)        — подготовить поле и состояние; первым делом вызвать activateScenario(id).
//                         retry — перезапуск после поражения.
//   stop()              — сценарий покидают (выход в меню или запуск другого): убрать своё состояние.
//   init()              — один раз при запуске страницы: найти свои элементы DOM, повесить обработчики.
//   syncUI()            — каждый кадр: показать или скрыть свои элементы DOM.
//   menuButton          — id кнопки сценария в главном меню.
//   retryOnDefeat()     — true, если перезапуск после поражения считается повтором (start получит retry = true).
//   updateStory(dt)     — кадр в состоянии 'story' (сюжетные сцены без боя).
//   updateBattle(dt)    — кадр боя до обновления врагов: появление врагов, колонны, свои объекты.
//   afterBattle(dt)     — конец кадра боя, если никто не погиб: проверка завершения волны или миссии.
//   keydown(e, held)    — клавиша; true — нажатие обработано и ядру не передаётся.
//   keyup(e), blur()    — отпускание клавиши и потеря фокуса окна.
//   fireBlocked()       — true, пока огонь с клавиатуры запрещён (например, клавиша закрывала диалог).
//   onEnemyKilled(e)    — враг уничтожен.
//   onEnemyEscaped(e)   — враг ушёл с поля через сценарный выезд (см. driveExit в enemy-ai.js).
//   updateMoto(e, dt)   — true, если сценарий сам провёл мотобригаду по своему маршруту.
//   aiMarkup()          — тактическая разметка карты сценария (формат — в enemy-tactics.js).
//   enemiesLeft()       — число врагов для HUD.
//   hudHint()           — строка-подсказка в HUD или null.
//   skipWave()          — кнопка разработчика «следующий эшелон».
//   countsStatistics()  — учитывать ли события статистики в состоянии 'story'.
//   cameraZoom()        — масштаб камеры вокруг игрока (1 — обычный вид).
//   draw(layer)         — свои слои кадра: 'ground' — поверх клеток, 'units' — поверх техники,
//                         'overlay' — поверх всего кадра.
//   drawFrame()         — true, если сценарий сам нарисовал весь кадр (замороженная финальная сцена).
//
// Поля врага, которые задаёт сценарий и понимает ядро:
//   storyWave   — номер сценарной волны (машина ведётся по сценарию);
//   storyExit   — столбец выезда у нижнего края: туда ведёт марш, там машина покидает поле;
//   storyColumn — общий массив машин одной колонны: они идут одной группой.

const SCENARIOS = {};
const DEFAULT_SCENARIO = 'waves';
const NO_SCENARIO = Object.freeze({ id: null });
// Активный сценарий (в меню — NO_SCENARIO) и сценарий, выбранный в меню для следующего старта.
let scenario = NO_SCENARIO,
  selectedScenario = DEFAULT_SCENARIO;

function defineScenario(id, definition) {
  SCENARIOS[id] = { id, ...definition };
}

// Делает сценарий активным; прежний сценарий убирает своё состояние.
function activateScenario(id) {
  if (scenario.id !== id && scenario.stop) scenario.stop();
  scenario = SCENARIOS[id];
}

function leaveScenario() {
  if (scenario.stop) scenario.stop();
  scenario = NO_SCENARIO;
}
